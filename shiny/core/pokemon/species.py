FIRST_HOENN_SPECIES = 277
UNUSED_SPECIES = 25


def gen3_name(species: int) -> str:
    if 1 <= species <= 251:
        return NAMES[species - 1]
    if FIRST_HOENN_SPECIES <= species <= FIRST_HOENN_SPECIES + len(NAMES) - 252:
        return NAMES[species - UNUSED_SPECIES - 1]
    return f"species #{species}"


def national_name(dex: int) -> str:
    return NAMES[dex - 1] if 1 <= dex <= len(NAMES) else f"species #{dex}"


